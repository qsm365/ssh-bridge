import { ref } from 'vue'

export type Locale = 'zh-CN' | 'en'

function savedLocale(): string | null {
  try { return typeof window === 'undefined' ? null : window.localStorage.getItem('ssh-bridge-locale') }
  catch { return null }
}

const saved = savedLocale()
export const locale = ref<Locale>(saved === 'en' ? 'en' : 'zh-CN')

if (typeof document !== 'undefined') document.documentElement.lang = locale.value

export function setLocale(value: Locale) {
  locale.value = value
  if (typeof document !== 'undefined') document.documentElement.lang = value
  try { window.localStorage.setItem('ssh-bridge-locale', value) } catch { /* Private browsing may block storage. */ }
}

